-- Section 03: tables with columns, defaults, constraints inline PK deferred, comments
-- (as one aggregated cell)
SELECT string_agg(tbl.stmt, E'\n\n' ORDER BY tbl.relname) AS ddl
FROM (
  SELECT c.relname,
    'CREATE TABLE public.' || quote_ident(c.relname) || E' (\n  ' ||
    cols.col_defs || E'\n);' ||
    COALESCE(E'\nCOMMENT ON TABLE public.' || quote_ident(c.relname) || ' IS ' ||
             quote_literal(obj_description(c.oid, 'pg_class')) || ';', '') ||
    COALESCE(E'\n' || cmt.col_comments, '') AS stmt
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN LATERAL (
    SELECT string_agg(
      quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) ||
      CASE
        WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
        WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
        WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
        WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
        ELSE ''
      END ||
      CASE WHEN a.attcollation <> 0 AND bt.typcollation <> a.attcollation
        THEN ' COLLATE ' || quote_ident(coll.collname) ELSE '' END ||
      CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
      E',\n  ' ORDER BY a.attnum
    ) AS col_defs
    FROM pg_attribute a
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    LEFT JOIN pg_type bt ON bt.oid = a.atttypid
    LEFT JOIN pg_collation coll ON coll.oid = a.attcollation
    WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
  ) cols ON true
  JOIN LATERAL (
    SELECT string_agg(
      'COMMENT ON COLUMN public.' || quote_ident(c.relname) || '.' || quote_ident(a.attname) ||
      ' IS ' || quote_literal(col_description(a.attrelid, a.attnum)) || ';',
      E'\n' ORDER BY a.attnum
    ) AS col_comments
    FROM pg_attribute a
    WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
      AND col_description(a.attrelid, a.attnum) IS NOT NULL
  ) cmt ON true
  WHERE n.nspname = 'public' AND c.relkind = 'r'
) tbl;
